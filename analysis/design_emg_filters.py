"""Design the on-board EMG filters for experiment 07 and write them as a C header.

    python analysis/design_emg_filters.py

Writes firmware/experiments/07_onboard_tension/components/emg_dsp/include/emg_coeffs.h.

Filters (fs = 1000 Hz), all second-order sections (biquads) run in single precision:
- Notches at 60, 120 and 180 Hz (scipy.signal.iirnotch). Q = f0 / 4, so every notch has a
  -3 dB bandwidth of 4 Hz: the same +/-2 Hz that experiment 06 removed offline. A narrower
  notch (higher Q) would settle more slowly (time constant ~ Q / (pi f0)) and could miss the
  mains if its frequency drifts; a wider one would remove more EMG. Harmonics from 240 Hz up
  lie above the band-pass and are attenuated by it instead.
- Band-pass 45-200 Hz, Butterworth, 4th-order prototype (8th-order band-pass, 4 sections):
  the band of experiment 06's main metric, with a flat pass band.

Experiment 06 filtered offline with zero-phase FFT masks; these filters are causal, so the
firmware output is delayed and not identical (see the experiment notes).
"""
from pathlib import Path

import numpy as np
from scipy import signal

FS = 1000
NOTCH_HZ = (60, 120, 180)
NOTCH_BW_HZ = 4.0
BAND = (45, 200)
BAND_ORDER = 4

REPO = Path(__file__).resolve().parent.parent
HEADER = REPO / "firmware/experiments/07_onboard_tension/components/emg_dsp/include/emg_coeffs.h"


def design():
    """All sections as rows (b0, b1, b2, a1, a2) with a0 = 1: notches first, then the band-pass."""
    rows, names = [], []
    for f0 in NOTCH_HZ:
        b, a = signal.iirnotch(f0, f0 / NOTCH_BW_HZ, fs=FS)
        rows.append([b[0] / a[0], b[1] / a[0], b[2] / a[0], a[1] / a[0], a[2] / a[0]])
        names.append(f"notch {f0} Hz, Q {f0 / NOTCH_BW_HZ:g}")
    sos = signal.butter(BAND_ORDER, BAND, btype="bandpass", fs=FS, output="sos")
    for k, sec in enumerate(sos):
        rows.append([sec[0], sec[1], sec[2], sec[4], sec[5]])
        names.append(f"band-pass {BAND[0]}-{BAND[1]} Hz, section {k + 1}/{len(sos)}")
    return np.array(rows), names


def as_sos(rows):
    return np.column_stack([rows[:, :3], np.ones(len(rows)), rows[:, 3:]])


def report(rows):
    sos = as_sos(rows)
    freqs = [20, 45, 60, 100, 120, 150, 180, 200, 300, 450]
    w, h = signal.sosfreqz(sos, worN=np.array(freqs, dtype=float), fs=FS)
    print("gain (dB):", ", ".join(f"{f} Hz {20 * np.log10(max(abs(g), 1e-12)):.1f}" for f, g in zip(freqs, h)))
    # Group delay at 100 Hz from the phase slope of the whole cascade.
    f = np.array([99.5, 100.5])
    _, hh = signal.sosfreqz(sos, worN=f, fs=FS)
    phase = np.unwrap(np.angle(hh))
    print(f"group delay at 100 Hz: {-(phase[1] - phase[0]) / (2 * np.pi * (f[1] - f[0])) * 1000:.1f} ms")


def write_header(rows, names):
    lines = [
        "// Generated by analysis/design_emg_filters.py -- do not edit by hand.",
        f"// fs = {FS} Hz. Each row: b0, b1, b2, a1, a2 (a0 = 1), Direct Form II transposed.",
        f"// Notches {', '.join(str(f) for f in NOTCH_HZ)} Hz (-3 dB bandwidth {NOTCH_BW_HZ:g} Hz each),",
        f"// then a Butterworth band-pass {BAND[0]}-{BAND[1]} Hz (order {BAND_ORDER} prototype).",
        "#pragma once",
        "",
        f"#define EMG_FS_HZ {FS}",
        f"#define EMG_NUM_SECTIONS {len(rows)}",
        "",
        "static const float EMG_SOS[EMG_NUM_SECTIONS][5] = {",
    ]
    for row, name in zip(rows, names):
        lines.append("    {" + ", ".join(f"{v:.9e}f" for v in row) + "},  // " + name)
    lines += ["};", ""]
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join(lines))
    print(f"wrote {HEADER.relative_to(REPO)}")


def main():
    rows, names = design()
    report(rows)
    write_header(rows, names)


if __name__ == "__main__":
    main()
